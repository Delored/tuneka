#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn utf16_offsets_preserve_ukrainian_and_surrogate_boundaries() {
        let text = "ї😀x";
        assert_eq!(utf8_offset(text, 0), 0);
        assert_eq!(utf8_offset(text, 1), 2);
        assert_eq!(utf8_offset(text, 3), 6);
        assert_eq!(utf8_offset(text, 4), 7);
        assert_eq!(utf8_offset(text, 100), text.len());
        assert!(text.is_char_boundary(utf8_offset(text, 2)));
    }
    #[test]
    fn ime_selection_is_relative_to_inserted_text_not_existing_prefix() {
        assert_eq!(marked_selection("ї😀x", &(1..3), 5), 7..11);
        assert_eq!(marked_selection("тест", &(0..4), 9), 9..17);
    }
    #[test]
    fn replacing_a_long_url_with_short_text_resets_horizontal_scroll() {
        assert_eq!(
            scroll_for_cursor(px(2000.), px(250.), px(800.), px(250.)),
            px(0.)
        );
        assert_eq!(
            scroll_for_cursor(px(0.), px(2000.), px(800.), px(2000.)),
            px(1208.)
        );
        assert_eq!(
            scroll_for_cursor(px(1208.), px(2000.), px(800.), px(0.)),
            px(0.)
        );
    }
}
