fn utf8_offset(text: &str, offset: usize) -> usize {
    let mut utf8_offset = 0;
    let mut utf16_count = 0;
    for ch in text.chars() {
        if utf16_count >= offset {
            break;
        }
        utf16_count += ch.len_utf16();
        utf8_offset += ch.len_utf8();
    }
    utf8_offset
}

fn marked_selection(text: &str, selection: &Range<usize>, base: usize) -> Range<usize> {
    base + utf8_offset(text, selection.start)..base + utf8_offset(text, selection.end)
}

fn scroll_for_cursor(current: Pixels, line_width: Pixels, width: Pixels, cursor: Pixels) -> Pixels {
    let mut scroll = current.min((line_width - width + px(8.)).max(px(0.)));
    if cursor < scroll {
        scroll = cursor;
    }
    if cursor > scroll + width - px(8.) {
        scroll = (cursor - width + px(8.)).max(px(0.));
    }
    scroll
}

